import test from 'node:test';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { mkdtempSync, writeFileSync, rmSync, chmodSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { protectedOscamBuild, OSCAM_SOURCE_REVISION } from '../src/oscam-integrity.mjs';

test('OSCam trust requires matching installed hash, source and receive policy', () => {
  const directory = mkdtempSync(join(tmpdir(), 'astra-oscam-integrity-'));
  try {
    const binary = join(directory, 'oscam'); const manifest = join(directory, 'manifest.json');
    const body = Buffer.from('disposable fixture executable');
    const hash = createHash('sha256').update(body).digest('hex');
    writeFileSync(binary, body, { mode: 0o755 });
    assert.equal(protectedOscamBuild(binary, manifest), false);
    const data = { policyVersion: 4, semanticPolicyVersion: 5, semanticSchedulerSha256: 'a'.repeat(64), sourceRevision: OSCAM_SOURCE_REVISION, binarySha256: hash };
    writeFileSync(manifest, JSON.stringify(data));
    assert.equal(protectedOscamBuild(binary, manifest), true);
    assert.equal(protectedOscamBuild(binary, manifest, { direct: true }), false, 'Legacy verified readers cannot silently enable direct transport');
    const direct = { ...data, directTransportPolicyVersion: 4, directTransportSha256: 'b'.repeat(64), providerBudgetSha256: 'c'.repeat(64) };
    writeFileSync(manifest, JSON.stringify(direct));
    assert.equal(protectedOscamBuild(binary, manifest, { direct: true }), true);
    writeFileSync(manifest, JSON.stringify({ ...direct, directTransportPolicyVersion: 1 }));
    assert.equal(protectedOscamBuild(binary, manifest, { direct: true }), false, 'Unhealthy account admission requires direct policy v2');
    writeFileSync(manifest, JSON.stringify({ ...direct, providerBudgetSha256: '' }));
    assert.equal(protectedOscamBuild(binary, manifest, { direct: true }), false);
    writeFileSync(manifest, JSON.stringify(data));
    writeFileSync(manifest, JSON.stringify({ ...data, experimental: true }));
    assert.equal(protectedOscamBuild(binary, manifest), false, 'Production must reject experimental reader binaries');
    assert.equal(protectedOscamBuild(binary, manifest, { allowExperimental: true }), true, 'Only explicit isolated-lab checks may opt in');
    assert.equal(protectedOscamBuild(binary, manifest), false, 'Lab verification must not authorize production through its cache');
    writeFileSync(manifest, JSON.stringify({ ...data, experimental: 'true' }));
    assert.equal(protectedOscamBuild(binary, manifest, { allowExperimental: true }), false);
    writeFileSync(manifest, JSON.stringify(data));
    chmodSync(binary, 0o644);
    assert.equal(protectedOscamBuild(binary, manifest), false);
    chmodSync(binary, 0o755);
    writeFileSync(binary, 'replacement executable');
    assert.equal(protectedOscamBuild(binary, manifest), false);
    writeFileSync(binary, body);
    writeFileSync(manifest, JSON.stringify({ ...data, policyVersion: 0 }));
    assert.equal(protectedOscamBuild(binary, manifest), false);
    writeFileSync(manifest, JSON.stringify({ ...data, sourceRevision: 'unverified' }));
    assert.equal(protectedOscamBuild(binary, manifest), false);
    writeFileSync(manifest, JSON.stringify({ ...data, policyVersion: 2, semanticPolicyVersion: 2 }));
    assert.equal(protectedOscamBuild(binary, manifest), false, 'Policy-v2 recovery must be rebuilt for this release');
    writeFileSync(manifest, JSON.stringify({ ...data, policyVersion: 3, semanticPolicyVersion: 3 }));
    assert.equal(protectedOscamBuild(binary, manifest), false, 'Idle network recovery requires policy-v4 reader');
    writeFileSync(manifest, JSON.stringify({ ...data, semanticPolicyVersion: 2 }));
    assert.equal(protectedOscamBuild(binary, manifest), false);
    writeFileSync(manifest, JSON.stringify({ ...data, semanticSchedulerSha256: '' }));
    assert.equal(protectedOscamBuild(binary, manifest), false);
    writeFileSync(manifest, 'not JSON');
    assert.equal(protectedOscamBuild(binary, manifest), false);
  } finally { rmSync(directory, { recursive: true, force: true }); }
});
